/**
 * Função utilitária para obter o preço acordado com o técnico para determinado tipo de serviço
 */
export function getTechnicianPriceForService(
  priceTable: TechnicianPriceTableItem[] | undefined,
  serviceName: string,
  fallbackPrice: number = 130.0
): number {
  if (!priceTable || !Array.isArray(priceTable) || priceTable.length === 0) {
    return fallbackPrice;
  }

  const cleanQuery = (serviceName || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
  if (!cleanQuery) return fallbackPrice;

  // 1. Match exato
  const exact = priceTable.find((item) => {
    const cleanItem = (item.serviceType || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
    return cleanItem === cleanQuery;
  });
  if (exact && typeof exact.prepostoPrice === 'number' && exact.prepostoPrice > 0) {
    return exact.prepostoPrice;
  }

  // 2. Match parcial / includes
  const partial = priceTable.find((item) => {
    const cleanItem = (item.serviceType || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
    return cleanItem && cleanQuery && (cleanQuery.includes(cleanItem) || cleanItem.includes(cleanQuery));
  });
  if (partial && typeof partial.prepostoPrice === 'number' && partial.prepostoPrice > 0) {
    return partial.prepostoPrice;
  }

  return fallbackPrice;
}
